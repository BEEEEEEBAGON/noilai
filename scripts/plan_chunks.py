def tier0_chunks(plan: dict, mc: dict) -> list[dict]:
    cpu = cpu_estimates()
    pilot = KRP.expand_set(PILOT_SET, plan, mc)
    out = [{"queue": "cpu", "tier": 0, "label": "first real run on CPU (smoke_20, 20 dev items)",
            "params": {"MODE": "first_run", "MODELS": ["gemma-3-1b-it"], "FORCED_CHOICE": True},
            "jobs": [{"run": "smoke_20", "models": ["gemma-3-1b-it"], "overrides": None, "tag": "cpu"}],
            "hours": [cpu["smoke_20"], cpu["smoke_20"]], "basis": "RL-2026-10-01-06 CPU benchmark, worst case"}]
    for m in pilot:
        s = CPU_PARAM_SCALE[m]
        hi = s * (cpu["smoke_20"] + cpu["pilot_t1_200"] + cpu["pilot_t1_200_forced_choice"] + cpu["pilot_xcopa_200"])
        out.append({"queue": "cpu", "tier": 0, "label": f"Gate 1 pilot on CPU: {m}",
                    "params": {"MODE": "pilot", "MODELS": [m], "FORCED_CHOICE": True},
                    "jobs": [{"run": r, "models": [m], "overrides": None, "tag": "cpu"}      # the CPU notebook's RUN_DIR_TAG
                             for r in ("smoke_20", "pilot_t1_200", "pilot_xcopa_200")],
                    "hours": [hi, hi], "basis": f"RL-2026-10-01-06 CPU benchmark x {s} (parameter ratio), worst case"})
    gp = [KRP.find_run(plan, r) for r in ("pilot_t1_200", "pilot_xcopa_200")]
    out.append({"queue": "gpu", "tier": 0, "label": "Gate 1 pilot on the T4 (the alternative to the CPU chunks; free quota "
                                                     "before the smoke week)",
                "params": {"SMOKE_RUN_IDS": [], "ALLOW_UNPINNED_REVISION": False},
                "jobs": [{"run": r["id"], "models": pilot, "overrides": None, "tag": None} for r in gp],
                "hours": [sum(r["estimate"]["low"] for r in gp), sum(r["estimate"]["high"] for r in gp)],
                "basis": "plan estimate"})
    sm, st = KRP.find_run(plan, "smoke_20"), KRP.find_run(plan, "smoke_20_tpu")
    t4 = [m for m in KRP.expand_models(sm, plan, mc) if HW_QUEUE.get(model_hw(m, mc)) == "gpu"]
    out.append({"queue": "gpu", "tier": 0, "label": "smoke week: every T4 / 2xT4 model on 20 dev items (panel freeze input)",
                "params": {"SMOKE_RUN_IDS": []},
                "jobs": [{"run": "smoke_20", "models": t4, "overrides": None, "tag": None}],
                "hours": [sm["estimate"]["low"], sm["estimate"]["high"]], "basis": "plan estimate"})
    out.append({"queue": "tpu", "tier": 0, "label": "smoke week: the TPU trio on 20 dev items",
                "params": {"SMOKE_RUN_IDS": []},
                "jobs": [{"run": "smoke_20_tpu", "models": KRP.expand_models(st, plan, mc), "overrides": None, "tag": None}],
                "hours": [st["estimate"]["low"], st["estimate"]["high"]], "basis": "plan estimate"})
    return out


def build_chunks(plan: dict | None = None, mc: dict | None = None) -> dict:
    plan = plan or KRP.load_plan()
    mc = mc or KRP.load_models()
    jobs, unscheduled = make_jobs(plan, mc)
    raw = tier0_chunks(plan, mc)
    for q in ("gpu", "tpu"):
        for js in pack(jobs, q, mc):
            raw.append({"queue": q, "tier": js[0]["tier"], "label": "models: " + ", ".join(dict.fromkeys(j["model"] for j in js)),
                        "params": {"SMOKE_RUN_IDS": []} if q == "tpu" else {},
                        "jobs": merge_jobs(js),
                        "hours": [sum(j["hours"][0] for j in js), sum(j["hours"][1] for j in js)],
                        "basis": "plan estimate, equal split per model; re-priced after the smoke week (DD 8.5)",
                        "unbooked_hours": [round(sum(j["hours"][i] for j in js if j["booked_on"].startswith("unbooked")), 2)
                                           for i in (0, 1)]})
    raw.sort(key=lambda c: (c["tier"], {"cpu": 0, "gpu": 1, "tpu": 2}[c["queue"]]))
    chunks = []
    for i, c in enumerate(raw, 1):
        cid = f"c{i:02d}_{c['queue']}_t{c['tier']}"
        keys = KRP.item_keys_for_runs(plan, list(dict.fromkeys(j["run"] for j in c["jobs"])))
        lo, hi = (round(x, 2) for x in c["hours"])
        ch = {"id": cid, "order": i, "queue": c["queue"], "tier": c["tier"], "tier_label": TIER_LABEL[c["tier"]],
              "window": WINDOW[c["tier"]], "label": c["label"], "base_notebook": QUEUE_NOTEBOOK[c["queue"]],
              "notebook": f"notebooks/chunks/{cid}.ipynb", "jobs": c["jobs"], "item_keys": keys,
              "hours": {"low": lo, "high": hi, "basis": c["basis"]},
              "quota_hours": ({"x1": [lo, hi], "x2": [round(2 * lo, 2), round(2 * hi, 2)]} if c["queue"] == "gpu"
                              else {"x1": [lo, hi]} if c["queue"] == "tpu" else {"x1": [0, 0]}),
              "params": c["params"]}
        if c.get("unbooked_hours") and any(c["unbooked_hours"]):
            ch["unbooked_hours"] = c["unbooked_hours"]
        chunks.append(ch)
    return {"version": 1, "generated_by": "scripts/plan_chunks.py", "run_plan": "configs/run_plan.yaml",
            "rules": {"order": "reverse of the pre-registered cut order (DD 7.1, DD 8.5); tiers in TIER_LABEL",
                      "estimate": "line estimate split equally over the line's models; plan estimate, not a measurement",
                      "session_cap_hours": SESSION_CAP_H, "session_overhead_hours_assumed": SESSION_OVERHEAD_H,
                      "first_of_family": first_of_family(plan, mc), "redundant": list(REDUNDANT),
                      "quota_readings": {"x1": "a 2xT4 session hour costs one quota hour",
                                         "x2": "a 2xT4 session hour costs two [UNCERTAIN: verify]"}},
            "tiers": TIER_LABEL, "not_chunked": NOT_CHUNKED, "unscheduled": unscheduled, "chunks": chunks}


# --------------------------------------------------------------------------------------------- notebooks
def _set_param(src: str, var: str, value, cid: str) -> str:
    text = pprint.pformat(value, width=100, sort_dicts=False)
    line = f"{var} = {text}   # chunk {cid} (scripts/plan_chunks.py)"
    pat = re.compile(rf"^{re.escape(var)} = .*$", re.MULTILINE)
    if pat.search(src):
        return pat.sub(lambda _m: line, src, count=1)
    return src.rstrip("\n") + "\n" + line + "\n"


def chunk_notebook(ch: dict) -> nbformat.NotebookNode:
    nb = copy.deepcopy(KBN.BUILDERS[ch["base_notebook"]]())
    i = next(k for k, c in enumerate(nb.cells) if c.cell_type == "code" and "# ---- parameters" in c.source)
    src = nb.cells[i].source
    params = dict(ch["params"])
    if ch["queue"] in ("gpu", "tpu"):
        params["JOBS"] = ch["jobs"]
        params["VERIFY_ITEM_KEYS"] = ch["item_keys"] + (["noilai_dev"] if ch["queue"] == "gpu" and "SMOKE_RUN_IDS" not in params else [])
        if ch["queue"] == "gpu":
            params["RUN_ID"] = ch["jobs"][0]["run"]
            params["MODELS"] = []
        else:
            params["RUN_IDS"] = list(dict.fromkeys(j["run"] for j in ch["jobs"]))
            params["MODELS"] = []
    else:
        params["RUN_IDS"] = [j["run"] for j in ch["jobs"]]
    params["RUN_LABEL"] = ch["id"]
    for var, value in params.items():
        src = _set_param(src, var, value, ch["id"])
    nb.cells[i].source = src
    q = ch["quota_hours"]
    cost = " / ".join(f"{k} {v[0]}–{v[1]} h" for k, v in q.items())
    lines = [f"# Compute chunk {ch['id']} (order {ch['order']}) — generated by `scripts/plan_chunks.py`; do not edit", "",
             (f"**Tier {ch['tier']}:** {ch['tier_label']}. **Window:** {ch['window']}. **Estimate:** "
              f"{ch['hours']['low']}–{ch['hours']['high']} h ({ch['hours']['basis']}); quota cost {cost} "
              "(the x1 / x2 readings of a 2xT4 hour: `docs/COMPUTE_PLAN.md`)."), "",
             "| run line | models | run-directory tag |", "|---|---|---|",
             *(f"| {j['run']} | {', '.join(j['models'])} | {j['tag'] or '—'} |" for j in ch["jobs"]), "",
             ("Resumable: every job runs `scripts/run_eval.py --resume`; outputs are pushed to the private runs dataset every "
              "`PUSH_EVERY_MINUTES` and after each model; `scripts/check_run.py` writes `stats.json` and `results_hashes.json` "
              "per run directory. If the session ends early, attach the runs dataset and run this notebook again: finished rows "
              "are skipped. The chunk is done when every job reports `ok`. Below is "
              f"`notebooks/{ch['base_notebook']}.ipynb` with its parameters cell preset (`JOBS`, `VERIFY_ITEM_KEYS`, `RUN_LABEL`).")]
    head = KBN.md("\n".join(lines))
    nb.cells.insert(0, head)
    nb.metadata["noilai"] = {**nb.metadata.get("noilai", {}), "chunk": ch["id"], "generator": "scripts/plan_chunks.py"}
    nbformat.validate(nb)
    return nb


