#!/usr/bin/env python
"""Compute chunks: `configs/run_plan.yaml` cut into Kaggle sessions, in the order that keeps what the
pre-registered cut order keeps longest (docs/COMPUTE_PLAN.md).

    python scripts/plan_chunks.py --write    # configs/compute_chunks.yaml, notebooks/chunks/*.ipynb and the
                                             # generated block of docs/COMPUTE_PLAN.md
    python scripts/plan_chunks.py --check    # drift check (tests/test_cloud.py)
    python scripts/plan_chunks.py --table    # print the generated tables

A chunk is one Kaggle session: an ordered list of jobs `{run, models, overrides, tag}` that the T4 / TPU notebook's
run cell executes with `--resume` (a chunk notebook is that notebook with its parameters cell preset). A job that
narrows its run line (`overrides`, e.g. the third paraphrase alone) writes its own run directory
`data/runs/<run>__<model>__<tag>` (kaggle_run_plan.narrow_run), so a later cut can drop it whole.

Order (the reverse of the pre-registered cut order: what is cut first runs last). DESIGN_DECISIONS 7.1 / PREREG:
"tokenizer-redundant models first (Gemma 3 12B, Qwen3.5-0.8B, Gemma 4 12B), then the second model of any family,
then seeds/paraphrases per 8.5"; DD 8.5: above 120 GPU-h, "E3's full arms are capped to the C1-informative families
and paraphrases drop to two for the TPU/2xT4 models before any model is cut in the 7.1 order". Tiers:

    0  pre-stage-2 lines on dev (smoke, pilot): not cuttable, and the only lines allowed before the stage-2 commit
    1  the first model of each family on every main line                       (cut last: never in the order)
    2  lines the cut order does not name, on tier-1 models: ablations, reasoning, bf16 drift
    3  the second model of a family                                             (cut stage 2 of DD 7.1)
    4  the tokenizer-redundant models                                           (cut stage 1 of DD 7.1)
    5  p2 of the TPU / 2xT4 models; E3 arms of families the census marks normalizing   (DD 8.5: cut before any model)

The 7.1 "seeds/paraphrases" stage (cut after the second models) is not split out: every model's p0-p2 run in one
job except where DD 8.5 needs p2 apart. Estimates: the plan's line estimate split EQUALLY over the line's models
(one stated rule; E1_main excludes the TPU trio that `tpu_main` books); a TPU model's share of a gpu_hours line is
spent on the TPU and booked on no plan line (flagged `unbooked`). Every number is "plan estimate, re-priced after
the smoke week" (DD 8.5 item 30); none is a measurement. Quota readings: x1 = a 2xT4 session hour costs one quota
hour, x2 = two [UNCERTAIN: verify in Kaggle's settings page].
"""
