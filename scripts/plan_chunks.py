def tables(spec: dict) -> str:
    plan = KRP.load_plan()
    q = plan.get("quota", {})
    gpu_w, tpu_w = q.get("kaggle_gpu_hours_per_week"), q.get("kaggle_tpu_hours_per_week")
    rows = ["| # | chunk | queue | tier | what | est. h (low–high) | quota h x1 | quota h x2 |", "|---|---|---|---|---|---|---|---|"]
    for c in spec["chunks"]:
        x2 = c["quota_hours"].get("x2", c["quota_hours"]["x1"])
        rows.append(f"| {c['order']} | `{c['id']}` | {c['queue']} | {c['tier']} | {c['label']} | {c['hours']['low']}–{c['hours']['high']} "
                    f"| {c['quota_hours']['x1'][0]}–{c['quota_hours']['x1'][1]} | {x2[0]}–{x2[1]} |")
    out = ["**Chunks, in run order** (estimates: plan line estimates split equally per model; not measurements):", "", *rows, ""]
    tot = ["| queue | tier | chunks | est. h low | est. h high | + session overhead (assumed) |", "|---|---|---|---|---|---|"]
    for qn in ("cpu", "gpu", "tpu"):
        for t in range(6):
            cs = [c for c in spec["chunks"] if c["queue"] == qn and c["tier"] == t]
            if cs:
                lo, hi = sum(c["hours"]["low"] for c in cs), sum(c["hours"]["high"] for c in cs)
                tot.append(f"| {qn} | {t} | {len(cs)} | {lo:.1f} | {hi:.1f} | {hi + SESSION_OVERHEAD_H * len(cs):.1f} |")
    out += ["**Totals by queue and tier:**", "", *tot, ""]
    cap = ["| stage-2 commit | test-split weeks to 22 Nov | GPU quota h (x1) | GPU clock h (x2) | TPU h | GPU tiers 1-5 fit at x1 (high + overhead) | at x2 |",
           "|---|---|---|---|---|---|---|"]
    gpu_post = [c for c in spec["chunks"] if c["queue"] == "gpu" and c["tier"] >= 1]

    def reach(capacity: float, factor: int) -> str:
        used, last = 0.0, None
        for c in gpu_post:
            need = factor * (c["hours"]["high"] + SESSION_OVERHEAD_H)
            if used + need > capacity:
                break
            used += need
            last = c
        if last is None:
            return "none"
        if last is gpu_post[-1]:
            return "all (through tier 5)"
        return f"through order {last['order']} (tier {last['tier']})"

    for label, weeks in STAGE2_SCENARIOS:
        cap.append(f"| {label} | {weeks} | {gpu_w * weeks} | {gpu_w * weeks // 2} | {tpu_w * weeks} | {reach(gpu_w * weeks, 1)} | "
                   f"{reach(gpu_w * weeks, 2)} |")
    out += [(f"**Capacity between the stage-2 commit and the results freeze** (quota {gpu_w} GPU-h and {tpu_w} TPU-h a week, "
             "`configs/run_plan.yaml` `quota`, secondary sources [UNCERTAIN: verify in Kaggle's settings]; one account):"), "", *cap, ""]
    if spec["unscheduled"]:
        out += ["**Unscheduled (no zero-cost route):** " + "; ".join(f"`{u['run']}` × `{u['model']}` ({u['hours'][0]}–{u['hours'][1]} h)"
                                                                     for u in spec["unscheduled"]), ""]
    unb = [c for c in spec["chunks"] if c.get("unbooked_hours")]
    if unb:
        lo, hi = sum(c["unbooked_hours"][0] for c in unb), sum(c["unbooked_hours"][1] for c in unb)
        out += [(f"**Unbooked TPU time:** the TPU models' equal shares of gpu_hours lines, {lo:.1f}–{hi:.1f} TPU-h, are booked on "
                 "no line of `plan_lines` (the plan's `tpu_models_and_bf16` line covers only tpu_main, the TPU smoke, reasoning and "
                 "bf16 drift)."), ""]
    return "\n".join(out)


def render_yaml(spec: dict) -> str:
    import yaml
    head = ("# configs/compute_chunks.yaml -- GENERATED by scripts/plan_chunks.py from configs/run_plan.yaml and\n"
            "# configs/models.yaml; do not edit (change the rules in the script, then --write). docs/COMPUTE_PLAN.md\n"
            "# explains the order (reverse of the pre-registered cut order) and the estimates (plan estimates, equal split\n"
            "# per model, re-priced after the smoke week; none is a measurement).\n")
    return head + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=120)


def doc_with_block(doc: str, block: str) -> str:
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"{COMPUTE_PLAN} lacks the generated-block markers")
    a, rest = doc.split(BEGIN, 1)
    _, b = rest.split(END, 1)
    return a + BEGIN + "\n" + block + "\n" + END + b


def write(spec: dict) -> list[Path]:
    out = []
    CHUNKS_YAML.write_text(render_yaml(spec), encoding="utf-8")
    out.append(CHUNKS_YAML)
    CHUNK_DIR.mkdir(parents=True, exist_ok=True)
    keep = set()
    for ch in spec["chunks"]:
        p = ROOT / ch["notebook"]
        keep.add(p.name)
        nb = chunk_notebook(ch)
        if p.exists():
            old = nbformat.read(str(p), as_version=4)
            if KBN.sources(old) == KBN.sources(nb):
                continue
            ids = {(c.cell_type, c.source): c.get("id") for c in old.cells}
            for c in nb.cells:
                if ids.get((c.cell_type, c.source)):
                    c["id"] = ids[(c.cell_type, c.source)]
        nbformat.write(nb, str(p))
        out.append(p)
    for p in CHUNK_DIR.glob("*.ipynb"):
        if p.name not in keep:
            p.unlink()
            out.append(p)
    if COMPUTE_PLAN.exists():
        doc = COMPUTE_PLAN.read_text(encoding="utf-8")
        new = doc_with_block(doc, tables(spec))
        if new != doc:
            COMPUTE_PLAN.write_text(new, encoding="utf-8")
            out.append(COMPUTE_PLAN)
    return out


def check(spec: dict) -> list[str]:
    problems = []
    if not CHUNKS_YAML.exists() or CHUNKS_YAML.read_text(encoding="utf-8") != render_yaml(spec):
        problems.append(f"{CHUNKS_YAML.relative_to(ROOT)} differs from the generator")
    names = set()
    for ch in spec["chunks"]:
        p = ROOT / ch["notebook"]
        names.add(p.name)
        if not p.exists():
            problems.append(f"{ch['notebook']}: missing")
        elif KBN.sources(nbformat.read(str(p), as_version=4)) != KBN.sources(chunk_notebook(ch)):
            problems.append(f"{ch['notebook']}: cell sources differ from the generator")
    extra = sorted(p.name for p in CHUNK_DIR.glob("*.ipynb") if p.name not in names) if CHUNK_DIR.exists() else []
    problems += [f"notebooks/chunks/{n}: not a chunk of the plan" for n in extra]
    if COMPUTE_PLAN.exists():
        doc = COMPUTE_PLAN.read_text(encoding="utf-8")
        if doc_with_block(doc, tables(spec)) != doc:
            problems.append("docs/COMPUTE_PLAN.md: generated block differs")
    else:
        problems.append("docs/COMPUTE_PLAN.md: missing")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--table", action="store_true")
    args = ap.parse_args(argv)
    spec = build_chunks()
    if args.table:
        print(tables(spec))
        return 0
    if args.write:
        for p in write(spec):
            print("[write]", p.relative_to(ROOT))
        return 0
    probs = check(spec)
    for p in probs:
        print("[drift]", p)
    print("[ok   ] chunks match the generator" if not probs else f"[FAIL ] {len(probs)} problem(s); run --write")
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
