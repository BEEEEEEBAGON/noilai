# --------------------------------------------------------------------------------------------- model roles
def model_hw(name: str, mc: dict) -> str:
    return mc["by_name"][name].get("hardware")


def first_of_family(plan: dict, mc: dict) -> dict[str, str]:
    """{family: lead model}: the pilot model of the family if it has one, else the first non-redundant self-hosted entry
    of configs/models.yaml (a scheduling rule, not a pre-registered one: docs/COMPUTE_PLAN.md, question to the author)."""
    pilot = KRP.expand_set(PILOT_SET, plan, mc)
    lead: dict[str, str] = {}
    for m in mc["models"]:
        if m.get("reference_of") or m.get("hardware") not in HW_QUEUE or m["name"] in REDUNDANT:
            continue
        fam = m.get("family")
        if fam not in lead or (m["name"] in pilot and lead[fam] not in pilot):
            lead[fam] = m["name"]
    return lead


def model_tier(name: str, plan: dict, mc: dict) -> int:
    """1 lead, 3 second of a family, 4 redundant (serving variants take their reference model's tier)."""
    base = mc["by_name"][name].get("reference_of") or name
    if base in REDUNDANT:
        return 4
    return 1 if base in first_of_family(plan, mc).values() else 3


def normalizes_nfd(name: str, mc: dict) -> bool:
    from noilai.eval.run import normalization_census_for
    c = normalization_census_for(mc["by_name"][name], {})
    return c.get("status") == "censused" and c.get("verdict_nfd") == "normalizes"


# --------------------------------------------------------------------------------------------- estimates
def booked_models(run: dict, plan: dict, mc: dict) -> list[str]:
    ms = KRP.expand_models(run, plan, mc)
    if run["id"] == "E1_main":                       # the TPU trio's part is booked under tpu_main (run_plan.yaml note)
        tpu_line = set(KRP.expand_models(KRP.find_run(plan, "tpu_main"), plan, mc))
        ms = [m for m in ms if m not in tpu_line]
    return ms


def share(run: dict, model: str, plan: dict, mc: dict) -> tuple[float, float, str]:
    """(low, high, booked_on): the line's estimate split equally over its models."""
    est = run["estimate"]
    n = len(booked_models(run, plan, mc))
    unit_q = {"gpu_hours": "gpu", "tpu_hours": "tpu"}.get(est["unit"])
    q = HW_QUEUE.get(model_hw(model, mc))
    if q is None:
        booked = None                                  # no queue for this hardware: make_jobs lists it as unscheduled
    else:
        booked = run.get("counts_toward") if unit_q == q else f"unbooked ({est['unit']} share run on the {q.upper()})"
    return est["low"] / n, est["high"] / n, booked


def cpu_estimates(bench: dict | None = None) -> dict:
    """Hours per CPU job for gemma-3-1b-it, derived from the RL-2026-10-01-06 benchmark (4 cores, float32): worst case
    64 new tokens per request, 8 forced-choice candidates per T1 item, XCOPA bounded by a 520-token prompt."""
    b = bench or json.loads(BENCH.read_text())
    dec520 = (b["generate_bs1_520p_24new_s"] - b["prefill_520_s"]) / 24
    dec950 = (b["generate_bs1_950p_24new_s"] - b["prefill_950_s"]) / 24
    gen_nfc, gen_nfd = b["prefill_520_s"] + 64 * dec520, b["prefill_950_s"] + 64 * dec950
    fc_nfc = b["prefill_520_s"] + 8 * b["continuation_3tok_on_cache_520_s"]
    fc_nfd = b["prefill_950_s"] + 8 * b["continuation_3tok_on_cache_950_s"]
    return {"smoke_20": 40 * gen_nfc / 3600,
            "pilot_t1_200": 200 * (gen_nfc + gen_nfd) / 3600,
            "pilot_t1_200_forced_choice": 200 * (fc_nfc + fc_nfd) / 3600,
            "pilot_xcopa_200": 200 * 2 * (b["prefill_520_s"] + 2 * b["continuation_3tok_on_cache_520_s"]) / 3600}


# --------------------------------------------------------------------------------------------- jobs
def make_jobs(plan: dict, mc: dict) -> tuple[list[dict], list[dict]]:
    """One job per (run, model[, paraphrase subset]) of every GPU/TPU line after tier 0; and the unscheduled ones."""
    jobs, unscheduled = [], []
    lines = [KRP.find_run(plan, r) for r in MAIN_LINES + OUTSIDE_LINES]
    for run in lines:
        for m in booked_models(run, plan, mc):
            hw = model_hw(m, mc)
            q = HW_QUEUE.get(hw)
            lo, hi, booked = share(run, m, plan, mc)
            if q is None:
                unscheduled.append({"run": run["id"], "model": m, "hours": [round(lo, 2), round(hi, 2)],
                                    "reason": f"configured for {hw!r}: no zero-cost route in the plan (Modal L4 needs a "
                                              "card on file, which this project does not use); question to the author"})
                continue
            tier = model_tier(m, plan, mc)
            if run["id"] in OUTSIDE_LINES and tier == 1 or run["id"] in ("reasoning_500", "reasoning_500_tpu"):
                tier = 2                              # reasoning is a sub-study of its own, outside the cut order
            if run["id"] in E3_LINES and normalizes_nfd(m, mc):
                tier = 5
            base = {"run": run["id"], "model": m, "queue": q, "booked_on": booked, "line_rank": (MAIN_LINES + OUTSIDE_LINES).index(run["id"])}
            if run["id"] in P2_SPLIT_LINES and hw in ("2xt4", "tpu") and run.get("paraphrases") == ["p0", "p1", "p2"]:
                jobs.append({**base, "tier": tier, "overrides": {"paraphrases": ["p0", "p1"]}, "tag": "p0p1",
                             "hours": [lo * 2 / 3, hi * 2 / 3]})
                jobs.append({**base, "tier": 5, "overrides": {"paraphrases": ["p2"]}, "tag": "p2", "hours": [lo / 3, hi / 3]})
            else:
                jobs.append({**base, "tier": tier, "overrides": None, "tag": None, "hours": [lo, hi]})
    return jobs, unscheduled


def model_order(mc: dict) -> dict[str, int]:
    return {m["name"]: i for i, m in enumerate(mc["models"])}


def pack(jobs: list[dict], queue: str, mc: dict) -> list[list[dict]]:
    """Greedy, tier-pure, model-major: a model's jobs of one tier stay in one chunk; a chunk books <= the cap."""
    order = model_order(mc)
    cap = SESSION_CAP_H[queue]
    chunks: list[list[dict]] = []
    for tier in range(1, 6):
        js = sorted((j for j in jobs if j["queue"] == queue and j["tier"] == tier),
                    key=lambda j: (order[j["model"]], j["line_rank"]))
        by_model: dict[str, list[dict]] = {}
        for j in js:
            by_model.setdefault(j["model"], []).append(j)
        cur, cur_h = [], 0.0
        for mjobs in by_model.values():
            h = sum(j["hours"][1] for j in mjobs)
            if h > cap:                                    # one model's tier work exceeds a session: split by job
                for j in mjobs:
                    if cur and cur_h + j["hours"][1] > cap:
                        chunks.append(cur)
                        cur, cur_h = [], 0.0
                    cur.append(j)
                    cur_h += j["hours"][1]
                continue
            if cur and cur_h + h > cap:
                chunks.append(cur)
                cur, cur_h = [], 0.0
            cur += mjobs
            cur_h += h
        if cur:
            chunks.append(cur)
    return chunks


def merge_jobs(js: list[dict]) -> list[dict]:
    """Notebook JOBS: run-major, consecutive models of one (run, overrides, tag) merged."""
    out: list[dict] = []
    for j in sorted(js, key=lambda j: j["line_rank"]):
        key = (j["run"], json.dumps(j["overrides"], sort_keys=True), j["tag"])
        if out and out[-1]["_key"] == key:
            out[-1]["models"].append(j["model"])
        else:
            out.append({"_key": key, "run": j["run"], "models": [j["model"]], "overrides": j["overrides"], "tag": j["tag"]})
    for o in out:
        del o["_key"]
    return out


