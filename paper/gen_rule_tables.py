# ------------------------------------------------------------------ placement pairs
def placement_pairs() -> list[tuple[str, str]]:
    """(new-style, old-style) spellings that differ between the two Hunspell lists.

    The two files hold the same syllables (6,611 lowercase entries each); exactly the
    entries present in one list and absent from the other are the ones whose tone-mark
    letter moves. Each new-only entry is mapped to its old-style spelling by the engine's
    own rule and must land in the old-only set; a mismatch is a bug in either the rule
    or the resource and stops the script."""
    new = set(L.load_hunspell_syllables("new"))
    old = set(L.load_hunspell_syllables("old"))
    only_new = sorted(new - old)
    only_old = old - new
    pairs = []
    for n in only_new:
        p = try_parse(n)
        if p is None:
            raise SystemExit(f"new-only Hunspell syllable does not parse: {n!r}")
        o = spell(p.syllable, style="old")
        if o not in only_old:
            raise SystemExit(f"rule maps {n!r} to {o!r}, which is not an old-only Hunspell entry")
        pairs.append((n, o))
    if len(pairs) != len(only_old):
        raise SystemExit(f"{len(pairs)} new-only vs {len(only_old)} old-only entries")
    return pairs


def placement_table(now: str, pairs: list[tuple[str, str]], ncol: int = 3) -> str:
    lines = [_hdr("placement", now)]
    lines.append(f"% {len(pairs)} pairs (new style, old style)")
    lines.append(r"\begin{table}[t]\centering\small")
    lines.append(r"\begin{tabular}{@{}" + "ll" * ncol + "@{}}")
    lines.append(r"\toprule")
    lines.append(" & ".join(["New & Old"] * ncol) + r" \\")
    lines.append(r"\midrule")
    nrow = -(-len(pairs) // ncol)
    for r in range(nrow):
        cells = []
        for c in range(ncol):
            i = c * nrow + r
            if i < len(pairs):
                cells.append(f"{pairs[i][0]} & {pairs[i][1]}")
            else:
                cells.append(" & ")
        lines.append(" & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(rf"\caption{{The {len(pairs)} syllables of the Hunspell vi\_VN list whose tone-mark letter differs between "
                 r"the new placement convention (mark on the nucleus letter) and the old one (mark on the first vowel letter "
                 r"of the open rimes oa, oe, uy). The set is the difference between the two released lists, and the engine's "
                 r"rule reproduces every pair; the C2 arm converts running text between the two conventions and changes "
                 r"exactly these syllables (and their capitalized forms).}")
    lines.append(r"\label{tab:placement}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ variants
VARIANT_EXAMPLES = {"V1": ("mèo", "cái"), "V2": ("đầu", "tiên"), "V3": ("bí", "mật"), "V4": ("bí", "mật"),
                    "V5": ("giải", "pháp"), "V6": ("mèo", "cái")}
# attested outputs the engine must reproduce (data/attested_seed.tsv; V5 from DESIGN_DECISIONS 3.6);
# a mismatch stops the script. V6 has no attested example: it is V1 read in the other order.
VARIANT_ATTESTED = {"V1": "mài kéo", "V2": "tiền đâu", "V3": "bị mất", "V4": "bật mí", "V5": "phải giáp"}


def variants_table(now: str) -> str:
    all_variants = getattr(V, "ALL_VARIANTS", V.VARIANTS)
    generated = set(V.VARIANTS)
    lines = [_hdr("variants", now)]
    lines.append(r"\begin{table}[t]\centering\small")
    lines.append(r"\begin{tabular}{@{}lllll@{}}")
    lines.append(r"\toprule")
    lines.append(r"Variant & Swapped & Kept in place & Engine example & Status \\")
    lines.append(r"\midrule")
    all_parts = ["onset", "rime", "tone"]
    for v in all_variants:
        if v not in VARIANT_EXAMPLES:
            continue
        moved = ", ".join(p for p in all_parts if p in V.MOVES[v])
        kept = ", ".join(p for p in all_parts if p not in V.MOVES[v])
        a, b = (try_parse(s).syllable for s in VARIANT_EXAMPLES[v])
        x, y = V.apply(v, a, b)
        out = f"{spell(x)} {spell(y)}"
        if v in VARIANT_ATTESTED and out != VARIANT_ATTESTED[v]:
            raise SystemExit(f"{v}: engine gives {out!r}, attested {VARIANT_ATTESTED[v]!r}")
        status = "generated cell" if v in generated else r"taxonomy; \task{T2} gold; \task{T3} twins"
        lines.append(rf"\var{{{v[1]}}} & {moved} & {kept} & \vi{{{' '.join(VARIANT_EXAMPLES[v])}}} $\rightarrow$ \vi{{{out}}} & {status} \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\caption{The six \vi{nói lái} variants as component permutations of a syllable pair "
                 r"(\texttt{noilai.gen.variants}): the non-empty proper subsets of \{onset, rime, tone\} exchanged between "
                 r"the two positions. Each is an involution; reading an output in the other order maps \var{1} to \var{6}, "
                 r"\var{2} to \var{3} and \var{4} to \var{5}, so \var{5} and \var{6} add no new unordered pair and are not "
                 r"generated as \task{T1} cells. Examples \var{1}--\var{5} are attested folk forms that the engine reproduces "
                 r"exactly; \var{6} has none.}")
    lines.append(r"\label{tab:variants}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "paper" / "tables")
    args = ap.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%MZ")
    written = {}
    (args.out / "rules_components.tex").write_text(components_table(now), encoding="utf-8")
    (args.out / "rules_onsets.tex").write_text(onsets_table(now), encoding="utf-8")
    (args.out / "rules_spelling.tex").write_text(spelling_table(now), encoding="utf-8")
    (args.out / "rules_variants.tex").write_text(variants_table(now), encoding="utf-8")
    pairs = placement_pairs()
    if len(pairs) != EXPECTED_PLACEMENT_PAIRS:
        raise SystemExit(f"expected {EXPECTED_PLACEMENT_PAIRS} placement pairs, found {len(pairs)}")
    (args.out / "rules_placement.tex").write_text(placement_table(now, pairs), encoding="utf-8")
    written = {"tables": sorted(p.name for p in args.out.glob("rules_*.tex")), "n_placement_pairs": len(pairs),
               "n_onsets": len(CANONICAL_ONSETS), "n_nuclei": len(NUCLEI), "n_codas": len(CODAS)}
    print(json.dumps(written, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
