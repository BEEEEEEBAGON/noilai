#!/usr/bin/env python
"""Appendix rule tables, generated from the parser's constants and the Hunspell lists.

    python paper/gen_rule_tables.py --out paper/tables

Writes
  rules_components.tex   the canonical symbol inventory (onsets, nuclei, codas, tones)
                         from noilai.vi.syllable / noilai.vi.unicode constants
  rules_onsets.tex       surface spelling of every canonical onset, with the c/k/q, g/gh,
                         ng/ngh triggers and the gi contraction, each example SPELLED BY
                         THE ENGINE (noilai.vi.syllable.spell); the plain rows take their
                         two examples from the ATTESTED inventory (noilai.vi.lexicon.
                         load_inventory), so that no row shows an engine-legal non-word
  rules_spelling.tex     the remaining spelling rules (glide letter, i/y, short a, coda
                         letters, stop-coda tones, open/closed nuclei, tone-mark placement)
                         with engine examples, plus the i/y EMISSION rule of the release
                         (noilai.vi.lexicon.emit), whose examples are computed by emit()
                         next to the speller's default so that the two cannot be confused
  rules_placement.tex    the 69 syllables whose tone-mark letter differs between the old
                         and the new placement convention: the set difference of the two
                         Hunspell lists, each pair checked against the engine's rule
  rules_variants.tex     the six noi lai variants (V1-V4 generated cells, V5-V6 taxonomy
                         rows) with the components they move and an engine-computed
                         example per variant

Every example is computed, never typed, so the tables cannot drift from the code. The
placement table needs data/external/vi-DauMoi.dic and vi-DauCu.dic (scripts/fetch_resources.py).
Vietnamese glosses are marked for native validation in the paper text, not here.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from noilai.gen import variants as V
from noilai.vi import lexicon as L
from noilai.vi import unicode as U
from noilai.vi.syllable import (
    CANONICAL_ONSETS,
    CLOSED_ONLY_NUCLEI,
    CODAS,
    NUCLEI,
    ONSET_SPELLINGS,
    OPEN_ONLY_NUCLEI,
    STOP_CODAS,
    Syllable,
    spell,
    try_parse,
)

EXPECTED_PLACEMENT_PAIRS = 69


def _hdr(name: str, now: str) -> str:
    return (f"% GENERATED by paper/gen_rule_tables.py ({name}) from noilai.vi.syllable constants "
            f"and the Hunspell lists; generated {now}. Do not edit by hand.\n")


def _tex(s: str) -> str:
    """Escape the few LaTeX specials that can occur in a spelling or a symbol."""
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
            .replace("#", r"\#").replace("_", r"\_").replace("$", r"\$"))


def _sym(s: str) -> str:
    return r"\texttt{" + (_tex(s) if s else r"$\varnothing$") + "}"


# ------------------------------------------------------------------ components
def components_table(now: str) -> str:
    lines = [_hdr("components", now)]
    lines.append(r"\begin{table*}[t]\centering\small")
    lines.append(r"\begin{tabular}{@{}lp{0.78\textwidth}@{}}")
    lines.append(r"\toprule")
    lines.append(r"Slot & Canonical symbols (as the parser writes them) \\")
    lines.append(r"\midrule")
    onsets = ", ".join(_sym(o) for o in CANONICAL_ONSETS)
    lines.append(rf"Onset ({len(CANONICAL_ONSETS)}) & {onsets}. "
                 r"\texttt{c} stands for /k/ however spelled (c, k, q); \texttt{g} for the voiced velar fricative "
                 r"however spelled (g, gh); \texttt{ng} for the velar nasal however spelled (ng, ngh); "
                 r"\texttt{gi} is the onset that contracts a following i; "
                 r"\texttt{p} occurs only in loanwords. \\")
    lines.append(r"Glide & present or absent (written \texttt{u} or \texttt{o}; the \texttt{u} of \texttt{qu} is the glide). \\")
    nuclei = ", ".join(_sym(n) for n in NUCLEI)
    lines.append(rf"Nucleus ({len(NUCLEI)}) & {nuclei}. Open-only (never take a coda): "
                 + ", ".join(_sym(n) for n in sorted(OPEN_ONLY_NUCLEI)) + r". Closed-only (always take a coda): "
                 + ", ".join(_sym(n) for n in sorted(CLOSED_ONLY_NUCLEI)) + r". \\")
    codas = ", ".join(_sym(c) for c in CODAS)
    lines.append(rf"Coda ({len(CODAS)}) & {codas}. \texttt{{j}} is the semivowel written i/y, \texttt{{w}} the semivowel "
                 r"written o/u; the stop codas " + ", ".join(_sym(c) for c in sorted(STOP_CODAS))
                 + r" take only the tones sắc and nặng. \\")
    tones = ", ".join(f"{i}~=~{_tex(vi)}" for i, vi in enumerate(U.TONE_NAMES_VI))
    lines.append(rf"Tone (6) & {tones}; index 0 (ngang) is the unmarked level tone, the other five carry a diacritic. \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\caption{The parser's canonical symbols (\texttt{noilai.vi.syllable}). A syllable is onset + rime + tone, "
                 r"the rime being glide$^?$ + nucleus + coda$^?$. Legality is decided against the attested inventory "
                 r"(Hunspell vi\_VN, both placement styles, extended with word-list syllables that reuse an attested rime).}")
    lines.append(r"\label{tab:components}")
    lines.append(r"\end{table*}")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ onsets
def _ex(onset: str, glide: bool, nucleus: str, coda: str = "", tone: int = 0) -> str:
    return spell(Syllable(onset=onset, glide=glide, nucleus=nucleus, coda=coda, tone=tone))


# (glide, nucleus, coda, tone) templates tried in order for the attested onset examples
ONSET_EXAMPLE_TEMPLATES = [
    (False, "a", "", 0), (False, "ô", "ng", 1), (False, "a", "ng", 0), (False, "i", "n", 0), (False, "ê", "n", 0),
    (False, "o", "n", 0), (False, "u", "ng", 0), (False, "a", "m", 0), (False, "i", "nh", 0), (False, "ư", "", 0),
    (False, "e", "", 0), (False, "ô", "", 0), (False, "â", "n", 2), (False, "a", "n", 2), (False, "i", "", 0),
    (False, "i", "p", 2), (False, "e", "p", 2), (False, "o", "", 2), (False, "u", "", 0), (False, "ê", "", 0),
]


def attested_examples(onset: str, n: int = 2) -> list[str]:
    """The first `n` ONSET_EXAMPLE_TEMPLATES that are attested syllables (exact syllable,
    tone included, in the release inventory), spelled by the engine. Fails loudly when
    the templates do not cover an onset, so that no table row falls back to a non-word."""
    inv = L.load_inventory()
    out = []
    for glide, nucleus, coda, tone in ONSET_EXAMPLE_TEMPLATES:
        syl = Syllable(onset=onset, glide=glide, nucleus=nucleus, coda=coda, tone=tone)
        if inv.is_attested(syl):
            out.append(spell(syl))
        if len(out) == n:
            return out
    raise SystemExit(f"fewer than {n} attested example syllables for onset {onset!r}; extend ONSET_EXAMPLE_TEMPLATES")


def onsets_table(now: str) -> str:
    # surface spellings per canonical onset, from the parser's spelling map
    surfaces: dict[str, list[str]] = {}
    for sp, canon in ONSET_SPELLINGS.items():
        surfaces.setdefault(canon, []).append(sp)
    lines = [_hdr("onsets", now)]
    lines.append(r"\begin{table}[t]\centering\small")
    lines.append(r"\begin{tabular}{@{}lll@{}}")
    lines.append(r"\toprule")
    lines.append(r"Onset & Written & Engine examples \\")
    lines.append(r"\midrule")
    for o in CANONICAL_ONSETS:
        if o == "":
            lines.append(rf"{_sym('')} & (nothing) & {_ex('', False, 'a')}, {_ex('', False, 'iê', 'n', 0)}, {_ex('', False, 'i', '', 2)} \\")
            continue
        written = ", ".join(sorted(surfaces.get(o, [o]), key=len))
        if o == "c":
            ex = f"{_ex('c', False, 'a')} / {_ex('c', False, 'e')} / {_ex('c', True, 'a')} (c before a, k before e \\^{{e}} i, q before the glide)"
        elif o == "g":
            ex = f"{_ex('g', False, 'a')} / {_ex('g', False, 'e')} (gh before e \\^{{e}} i)"
        elif o == "ng":
            ex = f"{_ex('ng', False, 'a')} / {_ex('ng', False, 'e')} / {_ex('ng', True, 'e')} (ngh before e \\^{{e}} i; not with a glide)"
        elif o == "gi":
            ex = f"{_ex('gi', False, 'a')} / {_ex('gi', False, 'i', '', 1)} / {_ex('gi', False, 'iê', 'ng')} (the rime's initial i is absorbed)"
        else:
            ex = ", ".join(attested_examples(o))
        lines.append(rf"{_sym(o)} & \texttt{{{_tex(written)}}} & {ex} \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\caption{Surface spelling of the canonical onsets. The k/gh/ngh spellings are triggered by the first "
                 r"\emph{written} letter after the onset (e, \^{e}, i), so a glide switches them off (\texttt{ngoe}, "
                 r"\texttt{nguy}); every example is produced by \texttt{noilai.vi.syllable.spell}, and the examples of "
                 r"the plain rows are attested syllables of the release inventory.}")
    lines.append(r"\label{tab:onsets}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ spelling rules
IY_EXAMPLE_WORDS = ("lí", "kĩ", "mĩ", "sĩ", "tỉ")


def _iy_emission_examples() -> str:
    """`emit(x)` next to `spell(x)` for the i/y example syllables, both computed, so that the
    released form and the speller's default are shown side by side and cannot be confused."""
    sylls = [try_parse(w, strict=False).syllable for w in IY_EXAMPLE_WORDS]
    emitted = ", ".join(L.emit(x) for x in sylls)
    default = ", ".join(spell(x) for x in sylls)
    return f"{emitted} (speller: {default})"


